export interface UiScreenBarProps {
  /** Заголовок экрана: он же `<h1>` (или другой уровень, см. `headingLevel`). */
  title: string
  /** Подпись кнопки «Назад» для скринридера. */
  backLabel?: string
  /** Если задан, «Назад» — ссылка (внутренние адреса превращает в переходы роутер оболочки); иначе кнопка и событие `back`. */
  backHref?: string
  /** Скрыть «Назад» (первый экран в потоке). */
  hideBack?: boolean
  /** Уровень заголовка: на странице второго уровня это обычно `h1`; в витрине с общим `h1` — `2` или `3`. */
  headingLevel?: 1 | 2 | 3
  /** Прилипает к верху окна при прокрутке. */
  sticky?: boolean
  /** Название области для скринридера. */
  label?: string
}
