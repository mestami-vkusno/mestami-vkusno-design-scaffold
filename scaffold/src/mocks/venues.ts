/*
  Заведения двух городов. Данные вымышлены для макета: адреса, телефоны и сайты условные
  (телефоны в диапазоне 555-01/02, сайты в зоне `.example`), юридически значимых фактов здесь нет.
  Особые случаи, которые нужны путям J1–J13, помечены в комментариях.
*/
import { CLOSED, everyDay, open, openIntervals, photo, weekly } from './builders'
import { dateAt } from './time'
import type { CityId, Photo, PhotoTone, Venue, VenueSocialLink, WeeklyHours } from './types'

type VenueSeed = Omit<Venue, 'slug' | 'gallery' | 'phone' | 'website' | 'socials'> & {
  /** Оттенки пяти снимков галереи: зал, блюдо, блюдо, интерьер, деталь. */
  readonly tones: readonly [PhotoTone, PhotoTone, PhotoTone, PhotoTone, PhotoTone]
  /** Порядковый номер для условного телефона. */
  readonly n: number
  readonly noContacts?: boolean
}

function phoneFor(cityId: CityId, n: number): string {
  const code = cityId === 'spb' ? '812' : '495'
  const block = cityId === 'spb' ? '01' : '02'
  return `+7 (${code}) 555-${block}-${String(n).padStart(2, '0')}`
}

function galleryOf(name: string, tones: VenueSeed['tones']): readonly Photo[] {
  const [hall, dishA, dishB, interior, detail] = tones
  return [
    photo('16:9', hall, `Зал, ${name}`),
    photo('1:1', dishA, `Блюдо, ${name}`),
    photo('4:3', dishB, `Блюдо, ${name}`),
    photo('3:4', interior, `Интерьер, ${name}`),
    photo('1:1', detail, `Деталь, ${name}`),
  ]
}

function socialsFor(id: string): readonly VenueSocialLink[] {
  return [
    { kind: 'telegram', url: `https://telegram.example/${id}` },
    { kind: 'vk', url: `https://vk.example/${id}` },
  ]
}

function build(seed: VenueSeed): Venue {
  const { tones, n, noContacts, ...rest } = seed
  const contacts = noContacts
    ? {}
    : { phone: phoneFor(seed.cityId, n), website: `https://${seed.id}.example`, socials: socialsFor(seed.id) }
  return { ...rest, slug: seed.id, gallery: galleryOf(seed.name, tones), ...contacts }
}

