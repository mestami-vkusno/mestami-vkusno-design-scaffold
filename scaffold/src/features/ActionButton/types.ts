import type { IconName } from '@/design-system'

export interface ActionButtonProps {
  icon: IconName
  /** Название действия для скринридера: «Нравится», «Комментарии». Число читается вместе с ним. */
  label: string
  /** Состояние «включено»: иконка заливается, кнопка получает `aria-pressed`. `undefined` — кнопка без состояния. */
  pressed?: boolean
  /** Число рядом с иконкой (лайки, комментарии). */
  count?: number
  /** Если задан, вместо кнопки рендерится ссылка (комментарии ведут на публикацию). */
  href?: string
  /** Иконка «подпрыгивает», когда состояние включается (только избранное и «нравится»). */
  bounce?: boolean
}
